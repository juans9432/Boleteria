-- Prestadores
CREATE INDEX IDX_PRESTADOR_MUNICIPIO
ON PRESTADOR(ID_MUNICIPIO);

CREATE INDEX IDX_PRESTADOR_TIPO
ON PRESTADOR(ID_TIPO_PRESTADOR);

-- Planes
CREATE INDEX IDX_PLAN_PRESTADOR
ON PLAN(ID_PRESTADOR);

-- Usuarios
CREATE INDEX IDX_USUARIO_PRESTADOR ON USUARIO_SISTEMA (ID_PRESTADOR);

CREATE INDEX IDX_USUARIO_ROL
ON USUARIO_SISTEMA(ID_ROL);

-- Reservas
CREATE INDEX IDX_RESERVA_PERFIL
ON RESERVA(ID_PERFIL);

CREATE INDEX IDX_RESERVA_PLAN
ON RESERVA(ID_PLAN);

-- Notificaciones
CREATE INDEX IDX_NOTIFICACION_USUARIO
ON NOTIFICACION(ID_USUARIO);

CREATE INDEX IDX_NOTIFICACION_RESERVA
ON NOTIFICACION(ID_RESERVA);

-- Atracciones y funciones
CREATE INDEX IDX_ATRACCION_PRESTADOR
ON ATRACCION(ID_PRESTADOR);

CREATE INDEX IDX_FUNCION_ATRACCION_FECHA
ON FUNCION(ID_ATRACCION, FECHA);

-- Boletas
CREATE INDEX IDX_BOLETA_RESERVA
ON BOLETA(ID_RESERVA);

CREATE INDEX IDX_BOLETA_ZONA_ESTADO
ON BOLETA(ID_ZONA, ESTADO);

CREATE INDEX IDX_BOLETA_TIPO_ENTRADA
ON BOLETA(ID_TIPO_ENTRADA);

CREATE INDEX IDX_BOLETA_COMBO
ON BOLETA(ID_COMBO);

-- Reportes de reservas por estado y fecha
CREATE INDEX IDX_RESERVA_ESTADO_FECHA
ON RESERVA(ESTADO, FECHA_HORA);


SELECT
    INDEX_NAME,
    TABLE_NAME,
    STATUS
FROM USER_INDEXES
WHERE INDEX_NAME LIKE 'IDX_%'
ORDER BY TABLE_NAME, INDEX_NAME;


SELECT COUNT(*) AS TOTAL_TRIGGERS
FROM USER_TRIGGERS;

CREATE INDEX IDX_RD_ZONA ON RESERVA_DETALLE (ID_ZONA);
CREATE INDEX IDX_RD_TIPO ON RESERVA_DETALLE (ID_TIPO_ENTRADA);
CREATE INDEX IDX_RD_COMBO ON RESERVA_DETALLE (ID_COMBO);

-- Oracle omite del índice las entradas en que ambas expresiones son NULL.
CREATE UNIQUE INDEX UK_BOLETA_LINEA_RESERVA ON BOLETA (
    CASE WHEN LINEA_RESERVA IS NOT NULL THEN ID_RESERVA END,
    LINEA_RESERVA
);
CREATE INDEX IDX_BOLETA_LINEA_RESERVA ON BOLETA (ID_RESERVA, LINEA_RESERVA);

CREATE UNIQUE INDEX UK_NOTIFICACION_EVENTO ON NOTIFICACION (CLAVE_EVENTO);

