-- 1. MUNICIPIO
CREATE TABLE MUNICIPIO (
    ID_MUNICIPIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(80) NOT NULL,
    DEPARTAMENTO VARCHAR2(60) NOT NULL,

    CONSTRAINT PK_MUNICIPIO
        PRIMARY KEY (ID_MUNICIPIO)
);

-- 2. TIPO_PRESTADOR
CREATE TABLE TIPO_PRESTADOR (
    ID_TIPO_PRESTADOR NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(60) NOT NULL,

    CONSTRAINT PK_TIPO_PRESTADOR
        PRIMARY KEY (ID_TIPO_PRESTADOR),

    CONSTRAINT UK_TIPO_PRESTADOR_NOMBRE
        UNIQUE (NOMBRE)
);

-- 3. ROL
CREATE TABLE ROL (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(40) NOT NULL,

    CONSTRAINT PK_ROL
        PRIMARY KEY (ID_ROL),

    CONSTRAINT UK_ROL_NOMBRE
        UNIQUE (NOMBRE)
);

-- 4. TIPO_ENTRADA
CREATE TABLE TIPO_ENTRADA (
    ID_TIPO_ENTRADA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(40) NOT NULL,
    PORCENTAJE_DESCUENTO NUMBER(5,2) DEFAULT 0 NOT NULL,
    REQUIERE_ADULTO CHAR(1) DEFAULT 'N' NOT NULL,

    CONSTRAINT PK_TIPO_ENTRADA
        PRIMARY KEY (ID_TIPO_ENTRADA),

    CONSTRAINT UK_TIPO_ENTRADA_NOMBRE
        UNIQUE (NOMBRE),

    CONSTRAINT CK_TIPO_ENTRADA_DESCUENTO
        CHECK (PORCENTAJE_DESCUENTO BETWEEN 0 AND 100),

    CONSTRAINT CK_TIPO_ENTRADA_ADULTO
        CHECK (REQUIERE_ADULTO IN ('S', 'N'))
);

-- 5. PRESTADOR
CREATE TABLE PRESTADOR (
    ID_PRESTADOR NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NIT VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(120) NOT NULL,
    CORREO VARCHAR2(100),
    ID_MUNICIPIO NUMBER NOT NULL,
    ID_TIPO_PRESTADOR NUMBER NOT NULL,

    CONSTRAINT PK_PRESTADOR
        PRIMARY KEY (ID_PRESTADOR),

    CONSTRAINT UK_PRESTADOR_NIT
        UNIQUE (NIT),

    CONSTRAINT FK_PRESTADOR_MUNICIPIO
        FOREIGN KEY (ID_MUNICIPIO)
        REFERENCES MUNICIPIO(ID_MUNICIPIO),

    CONSTRAINT FK_PRESTADOR_TIPO
        FOREIGN KEY (ID_TIPO_PRESTADOR)
        REFERENCES TIPO_PRESTADOR(ID_TIPO_PRESTADOR)
);

-- 6. PLAN
CREATE TABLE PLAN (
    ID_PLAN NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    ESTADO VARCHAR2(10) NOT NULL,
    ID_PRESTADOR NUMBER NOT NULL,

    CONSTRAINT PK_PLAN
        PRIMARY KEY (ID_PLAN),

    CONSTRAINT CK_PLAN_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),

    CONSTRAINT FK_PLAN_PRESTADOR
        FOREIGN KEY (ID_PRESTADOR)
        REFERENCES PRESTADOR(ID_PRESTADOR)
);

-- 7. USUARIO_SISTEMA
CREATE TABLE USUARIO_SISTEMA (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CORREO VARCHAR2(100) NOT NULL,
    CLAVE_HASH VARCHAR2(255) NOT NULL,
    ESTADO VARCHAR2(10) NOT NULL,
    ID_ROL NUMBER NOT NULL,
    ID_PRESTADOR NUMBER,

    CONSTRAINT PK_USUARIO_SISTEMA
        PRIMARY KEY (ID_USUARIO),

    CONSTRAINT UK_USUARIO_CORREO
        UNIQUE (CORREO),

    CONSTRAINT CK_USUARIO_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),

    CONSTRAINT FK_USUARIO_ROL
        FOREIGN KEY (ID_ROL)
        REFERENCES ROL(ID_ROL),

    CONSTRAINT FK_USUARIO_PRESTADOR
        FOREIGN KEY (ID_PRESTADOR)
        REFERENCES PRESTADOR(ID_PRESTADOR)
);

-- 8. PERFIL_CLIENTE
CREATE TABLE PERFIL_CLIENTE (
    ID_PERFIL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DOCUMENTO VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(20),
    ID_USUARIO NUMBER,

    CONSTRAINT PK_PERFIL_CLIENTE
        PRIMARY KEY (ID_PERFIL),

    CONSTRAINT UK_PERFIL_DOCUMENTO
        UNIQUE (DOCUMENTO),

    CONSTRAINT UK_PERFIL_USUARIO
        UNIQUE (ID_USUARIO),

    CONSTRAINT FK_PERFIL_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO_SISTEMA(ID_USUARIO)
);

-- 9. ATRACCION
CREATE TABLE ATRACCION (
    ID_ATRACCION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(120) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    ID_PRESTADOR NUMBER NOT NULL,

    CONSTRAINT PK_ATRACCION
        PRIMARY KEY (ID_ATRACCION),

    CONSTRAINT FK_ATRACCION_PRESTADOR
        FOREIGN KEY (ID_PRESTADOR)
        REFERENCES PRESTADOR(ID_PRESTADOR)
);

-- 10. FUNCION
CREATE TABLE FUNCION (
    ID_FUNCION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FECHA DATE NOT NULL,
    HORA_APERTURA VARCHAR2(5) NOT NULL,
    HORA_CIERRE VARCHAR2(5) NOT NULL,
    ESTADO VARCHAR2(12) NOT NULL,
    ID_ATRACCION NUMBER NOT NULL,

    CONSTRAINT PK_FUNCION
        PRIMARY KEY (ID_FUNCION),

    CONSTRAINT CK_FUNCION_ESTADO
        CHECK (ESTADO IN (
            'PROGRAMADA', 'CANCELADA', 'REALIZADA'
        )),

    CONSTRAINT CK_FUNCION_HORARIO
        CHECK (HORA_CIERRE > HORA_APERTURA),

    CONSTRAINT FK_FUNCION_ATRACCION
        FOREIGN KEY (ID_ATRACCION)
        REFERENCES ATRACCION(ID_ATRACCION)
);

-- 11. ZONA
CREATE TABLE ZONA (
    ID_ZONA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(40) NOT NULL,
    AFORO NUMBER(6) NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    ID_FUNCION NUMBER NOT NULL,

    CONSTRAINT PK_ZONA
        PRIMARY KEY (ID_ZONA),

    CONSTRAINT UK_ZONA_FUNCION_NOMBRE
        UNIQUE (ID_FUNCION, NOMBRE),

    CONSTRAINT CK_ZONA_AFORO
        CHECK (AFORO > 0),

    CONSTRAINT CK_ZONA_PRECIO
        CHECK (PRECIO > 0),

    CONSTRAINT FK_ZONA_FUNCION
        FOREIGN KEY (ID_FUNCION)
        REFERENCES FUNCION(ID_FUNCION)
        ON DELETE CASCADE
);

-- 12. COMBO
CREATE TABLE COMBO (
    ID_COMBO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,
    DIAS_VIGENCIA NUMBER(3) NOT NULL,
    ESTADO VARCHAR2(10) NOT NULL,

    CONSTRAINT PK_COMBO
        PRIMARY KEY (ID_COMBO),

    CONSTRAINT CK_COMBO_PRECIO
        CHECK (PRECIO > 0),

    CONSTRAINT CK_COMBO_VIGENCIA
        CHECK (DIAS_VIGENCIA >= 1),

    CONSTRAINT CK_COMBO_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- 13. COMBO_ATRACCION
CREATE TABLE COMBO_ATRACCION (
    ID_COMBO NUMBER NOT NULL,
    ID_ATRACCION NUMBER NOT NULL,
    PORCENTAJE_PRECIO NUMBER(5,2) NOT NULL,

    CONSTRAINT PK_COMBO_ATRACCION
        PRIMARY KEY (ID_COMBO, ID_ATRACCION),

    CONSTRAINT CK_COMBO_ATRACCION_PORCENTAJE
        CHECK (PORCENTAJE_PRECIO BETWEEN 1 AND 100),

    CONSTRAINT FK_COMBO_ATRACCION_COMBO
        FOREIGN KEY (ID_COMBO)
        REFERENCES COMBO(ID_COMBO)
        ON DELETE CASCADE,

    CONSTRAINT FK_COMBO_ATRACCION_ATRACCION
        FOREIGN KEY (ID_ATRACCION)
        REFERENCES ATRACCION(ID_ATRACCION)
);

-- 14. RESERVA
CREATE TABLE RESERVA (
    ID_RESERVA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL,
    ID_PERFIL NUMBER NOT NULL,
    ID_PLAN NUMBER,

    CONSTRAINT PK_RESERVA
        PRIMARY KEY (ID_RESERVA),

    CONSTRAINT CK_RESERVA_ESTADO
        CHECK (ESTADO IN (
            'PENDIENTE', 'CONFIRMADA',
            'EXPIRADA', 'CANCELADA'
        )),

    CONSTRAINT FK_RESERVA_PERFIL
        FOREIGN KEY (ID_PERFIL)
        REFERENCES PERFIL_CLIENTE(ID_PERFIL),

    CONSTRAINT FK_RESERVA_PLAN
        FOREIGN KEY (ID_PLAN)
        REFERENCES PLAN(ID_PLAN)
        ON DELETE SET NULL
);

-- 15. NOTIFICACION
CREATE TABLE NOTIFICACION (
    ID_NOTIFICACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ASUNTO VARCHAR2(120),
    MENSAJE VARCHAR2(500) NOT NULL,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LEIDA CHAR(1) DEFAULT 'N' NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    ID_RESERVA NUMBER,
    CLAVE_EVENTO VARCHAR2(150 CHAR),

    CONSTRAINT PK_NOTIFICACION
        PRIMARY KEY (ID_NOTIFICACION),

    CONSTRAINT CK_NOTIFICACION_LEIDA
        CHECK (LEIDA IN ('S', 'N')),

    CONSTRAINT FK_NOTIFICACION_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO_SISTEMA(ID_USUARIO)
        ON DELETE CASCADE,

    CONSTRAINT FK_NOTIFICACION_RESERVA
        FOREIGN KEY (ID_RESERVA)
        REFERENCES RESERVA(ID_RESERVA)
        ON DELETE SET NULL
);

-- 16. BOLETA
CREATE TABLE BOLETA (
    ID_BOLETA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO VARCHAR2(36) NOT NULL,
    ESTADO VARCHAR2(10) DEFAULT 'VENDIDA' NOT NULL,
    PRECIO_PAGADO NUMBER(10,2) NOT NULL,
    ID_RESERVA NUMBER NOT NULL,
    ID_ZONA NUMBER NOT NULL,
    ID_TIPO_ENTRADA NUMBER NOT NULL,
    ID_COMBO NUMBER,
    LINEA_RESERVA NUMBER(8),

    CONSTRAINT PK_BOLETA
        PRIMARY KEY (ID_BOLETA),

    CONSTRAINT UK_BOLETA_CODIGO
        UNIQUE (CODIGO),

    CONSTRAINT CK_BOLETA_ESTADO
        CHECK (ESTADO IN ('VENDIDA', 'USADA', 'ANULADA')),

    CONSTRAINT CK_BOLETA_PRECIO
        CHECK (PRECIO_PAGADO >= 0),

    CONSTRAINT FK_BOLETA_RESERVA
        FOREIGN KEY (ID_RESERVA)
        REFERENCES RESERVA(ID_RESERVA),

    CONSTRAINT FK_BOLETA_ZONA
        FOREIGN KEY (ID_ZONA)
        REFERENCES ZONA(ID_ZONA),

    CONSTRAINT FK_BOLETA_TIPO_ENTRADA
        FOREIGN KEY (ID_TIPO_ENTRADA)
        REFERENCES TIPO_ENTRADA(ID_TIPO_ENTRADA),

    CONSTRAINT FK_BOLETA_COMBO
        FOREIGN KEY (ID_COMBO)
        REFERENCES COMBO(ID_COMBO)
);


-- 17. RESERVA_DETALLE

-- Cada linea representa una entrada. El grupo identifica una unidad del combo.
CREATE TABLE RESERVA_DETALLE (
    ID_RESERVA NUMBER NOT NULL,
    LINEA NUMBER(8) NOT NULL,
    ID_ZONA NUMBER NOT NULL,
    ID_TIPO_ENTRADA NUMBER NOT NULL,
    ID_COMBO NUMBER,
    GRUPO_COMBO NUMBER(8),
    PRECIO_ORIENTATIVO NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_RESERVA_DETALLE PRIMARY KEY (ID_RESERVA, LINEA),
    CONSTRAINT FK_RD_RESERVA FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
    CONSTRAINT FK_RD_ZONA FOREIGN KEY (ID_ZONA) REFERENCES ZONA(ID_ZONA),
    CONSTRAINT FK_RD_TIPO FOREIGN KEY (ID_TIPO_ENTRADA) REFERENCES TIPO_ENTRADA(ID_TIPO_ENTRADA),
    CONSTRAINT FK_RD_COMBO FOREIGN KEY (ID_COMBO) REFERENCES COMBO(ID_COMBO),
    CONSTRAINT CK_RD_LINEA CHECK (LINEA > 0),
    CONSTRAINT CK_RD_PRECIO CHECK (PRECIO_ORIENTATIVO >= 0),
    CONSTRAINT CK_RD_GRUPO CHECK (
        (ID_COMBO IS NULL AND GRUPO_COMBO IS NULL)
        OR (ID_COMBO IS NOT NULL AND GRUPO_COMBO IS NOT NULL AND GRUPO_COMBO > 0)
    )
);

