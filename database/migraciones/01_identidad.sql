-- Ejecutar en XEPDB1 con el esquema de Boletería como esquema actual.
-- El DDL de Oracle confirma cada cambio. Las comprobaciones permiten reanudar.
DECLARE
    v_esquema VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM ALL_TAB_COLUMNS
    WHERE OWNER = v_esquema AND TABLE_NAME = 'PERFIL_CLIENTE'
      AND COLUMN_NAME = 'ID_USUARIO' AND NULLABLE = 'N';
    IF v_existe = 1 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PERFIL_CLIENTE MODIFY (ID_USUARIO NULL)';
    END IF;

    SELECT COUNT(*) INTO v_existe FROM ALL_TAB_COLUMNS
    WHERE OWNER = v_esquema AND TABLE_NAME = 'USUARIO_SISTEMA'
      AND COLUMN_NAME = 'ID_PRESTADOR';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE USUARIO_SISTEMA ADD (ID_PRESTADOR NUMBER)';
    END IF;

    SELECT COUNT(*) INTO v_existe FROM ALL_CONSTRAINTS
    WHERE OWNER = v_esquema AND CONSTRAINT_NAME = 'FK_USUARIO_PRESTADOR';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE USUARIO_SISTEMA ADD CONSTRAINT FK_USUARIO_PRESTADOR '
                          || 'FOREIGN KEY (ID_PRESTADOR) REFERENCES PRESTADOR(ID_PRESTADOR)';
    END IF;

    SELECT COUNT(*) INTO v_existe FROM ALL_INDEXES
    WHERE OWNER = v_esquema AND INDEX_NAME = 'IDX_USUARIO_PRESTADOR';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_USUARIO_PRESTADOR ON USUARIO_SISTEMA (ID_PRESTADOR)';
    END IF;
END;
/

INSERT INTO ROL (NOMBRE)
SELECT 'ENCARGADO_PRESTADOR' FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM ROL WHERE NOMBRE = 'ENCARGADO_PRESTADOR');

COMMIT;
