    FROM DUAL

    UNION ALL

    SELECT '1000000001',
           TIMESTAMP '2026-11-05 09:10:00',
           'Experiencia Cafetera',
           'Mirador Cafetero',
           DATE '2026-11-22'
    FROM DUAL

