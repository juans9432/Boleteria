
-- =========================================================
-- REPORTE 1: PROXIMAS FUNCIONES TURISTICAS
-- =========================================================

SELECT
    F.ID_FUNCION,
    A.NOMBRE AS ATRACCION,
    P.NOMBRE AS PRESTADOR,
    M.NOMBRE AS MUNICIPIO,
    TO_CHAR(F.FECHA, 'DD/MM/YYYY') AS FECHA,
    F.HORA_APERTURA,
    F.HORA_CIERRE,
    F.ESTADO
FROM FUNCION F
JOIN ATRACCION A
    ON F.ID_ATRACCION = A.ID_ATRACCION
JOIN PRESTADOR P
    ON A.ID_PRESTADOR = P.ID_PRESTADOR
JOIN MUNICIPIO M
    ON P.ID_MUNICIPIO = M.ID_MUNICIPIO
WHERE F.ESTADO = 'PROGRAMADA'
  AND F.FECHA >= TRUNC(CURRENT_DATE)
ORDER BY F.FECHA, F.HORA_APERTURA;



-- =========================================================
-- REPORTE 2: RESERVAS POR CLIENTE
-- =========================================================

SELECT
    P.ID_PERFIL,
    P.DOCUMENTO,
    P.NOMBRE AS CLIENTE,
    R.ID_RESERVA,
    R.FECHA_HORA,
    R.ESTADO,
    NVL(PL.NOMBRE, 'SIN PLAN') AS PLAN_TURISTICO
FROM PERFIL_CLIENTE P
JOIN RESERVA R
    ON P.ID_PERFIL = R.ID_PERFIL
LEFT JOIN PLAN PL
    ON R.ID_PLAN = PL.ID_PLAN
ORDER BY P.NOMBRE, R.FECHA_HORA DESC;



-- =========================================================
-- REPORTE 3: COMPROBANTE DE COMPRA O RESUMEN DE RESERVA PENDIENTE
-- =========================================================

SELECT
    R.ID_RESERVA,
    P.NOMBRE AS CLIENTE,
    P.DOCUMENTO,
    R.FECHA_HORA,
    R.ESTADO AS ESTADO_RESERVA,
    B.CODIGO AS CODIGO_BOLETA,
    A.NOMBRE AS ATRACCION,
    F.FECHA AS FECHA_FUNCION,
    Z.NOMBRE AS ZONA,
    T.NOMBRE AS TIPO_ENTRADA,
    NVL(C.NOMBRE, 'INDIVIDUAL') AS COMBO,
    B.PRECIO_PAGADO,
    'COMPROBANTE_COMPRA' AS TIPO_DOCUMENTO,
    CAST(NULL AS NUMBER) AS PRECIO_ORIENTATIVO,
    CAST(NULL AS NUMBER) AS TOTAL_ORIENTATIVO,
    SUM(B.PRECIO_PAGADO) OVER (
        PARTITION BY R.ID_RESERVA
    ) AS TOTAL_RESERVA
FROM RESERVA R
JOIN PERFIL_CLIENTE P
    ON R.ID_PERFIL = P.ID_PERFIL
JOIN BOLETA B
    ON R.ID_RESERVA = B.ID_RESERVA
JOIN ZONA Z
    ON B.ID_ZONA = Z.ID_ZONA
JOIN FUNCION F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCION A
    ON F.ID_ATRACCION = A.ID_ATRACCION
JOIN TIPO_ENTRADA T
    ON B.ID_TIPO_ENTRADA = T.ID_TIPO_ENTRADA
LEFT JOIN COMBO C
    ON B.ID_COMBO = C.ID_COMBO
WHERE R.ESTADO = 'CONFIRMADA'
  AND B.ESTADO IN ('VENDIDA', 'USADA')
UNION ALL
SELECT
    R.ID_RESERVA, P.NOMBRE, P.DOCUMENTO, R.FECHA_HORA, R.ESTADO,
    CAST(NULL AS VARCHAR2(36)), A.NOMBRE, F.FECHA, Z.NOMBRE, T.NOMBRE,
    NVL(C.NOMBRE, 'INDIVIDUAL'), CAST(NULL AS NUMBER),
    'RESUMEN_PENDIENTE', D.PRECIO_ORIENTATIVO,
    SUM(D.PRECIO_ORIENTATIVO) OVER (PARTITION BY R.ID_RESERVA),
    CAST(NULL AS NUMBER)
FROM RESERVA R
JOIN PERFIL_CLIENTE P ON P.ID_PERFIL = R.ID_PERFIL
JOIN RESERVA_DETALLE D ON D.ID_RESERVA = R.ID_RESERVA
JOIN ZONA Z ON Z.ID_ZONA = D.ID_ZONA
JOIN FUNCION F ON F.ID_FUNCION = Z.ID_FUNCION
JOIN ATRACCION A ON A.ID_ATRACCION = F.ID_ATRACCION
JOIN TIPO_ENTRADA T ON T.ID_TIPO_ENTRADA = D.ID_TIPO_ENTRADA
LEFT JOIN COMBO C ON C.ID_COMBO = D.ID_COMBO
WHERE R.ESTADO = 'PENDIENTE'
  AND R.FECHA_HORA > CAST(SYSTIMESTAMP AT TIME ZONE 'America/Bogota' AS TIMESTAMP)
      - INTERVAL '15' MINUTE
  AND NOT EXISTS (SELECT 1 FROM BOLETA B WHERE B.ID_RESERVA = R.ID_RESERVA)
ORDER BY ID_RESERVA, CODIGO_BOLETA;



-- =========================================================
-- REPORTE 4: OCUPACION POR ZONA
-- =========================================================

SELECT
    A.NOMBRE AS ATRACCION,
    F.ID_FUNCION,
    F.FECHA,
    Z.ID_ZONA,
    Z.NOMBRE AS ZONA,
    Z.AFORO,
    COUNT(
        CASE
            WHEN B.ESTADO IN ('VENDIDA', 'USADA')
            THEN B.ID_BOLETA
        END
    ) AS CUPOS_OCUPADOS,
    Z.AFORO - COUNT(
        CASE
            WHEN B.ESTADO IN ('VENDIDA', 'USADA')
            THEN B.ID_BOLETA
        END
    ) AS CUPOS_DISPONIBLES,
    ROUND(
        COUNT(
            CASE
                WHEN B.ESTADO IN ('VENDIDA', 'USADA')
                THEN B.ID_BOLETA
            END
        ) * 100 / Z.AFORO,
        2
    ) AS PORCENTAJE_OCUPACION
FROM ZONA Z
JOIN FUNCION F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCION A
    ON F.ID_ATRACCION = A.ID_ATRACCION
LEFT JOIN BOLETA B
    ON Z.ID_ZONA = B.ID_ZONA
GROUP BY
    A.NOMBRE,
    F.ID_FUNCION,
    F.FECHA,
    Z.ID_ZONA,
    Z.NOMBRE,
    Z.AFORO
ORDER BY F.FECHA, A.NOMBRE, Z.NOMBRE;



-- =========================================================
-- REPORTE 5: INGRESOS POR ATRACCION Y TIPO DE ENTRADA
-- =========================================================

SELECT
    A.NOMBRE AS ATRACCION,
    T.NOMBRE AS TIPO_ENTRADA,
    COUNT(B.ID_BOLETA) AS BOLETAS_VENDIDAS,
    SUM(B.PRECIO_PAGADO) AS TOTAL_INGRESOS,
    ROUND(AVG(B.PRECIO_PAGADO), 2) AS PRECIO_PROMEDIO
FROM BOLETA B
JOIN ZONA Z
    ON B.ID_ZONA = Z.ID_ZONA
JOIN FUNCION F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCION A
    ON F.ID_ATRACCION = A.ID_ATRACCION
JOIN TIPO_ENTRADA T
    ON B.ID_TIPO_ENTRADA = T.ID_TIPO_ENTRADA
JOIN RESERVA R
    ON B.ID_RESERVA = R.ID_RESERVA
WHERE B.ESTADO IN ('VENDIDA', 'USADA')
  AND R.ESTADO = 'CONFIRMADA'
GROUP BY A.NOMBRE, T.NOMBRE
ORDER BY TOTAL_INGRESOS DESC;



-- =========================================================
-- REPORTE 6: RESERVAS POR MES Y ESTADO
-- =========================================================

SELECT
    TO_CHAR(R.FECHA_HORA, 'YYYY-MM') AS MES,
    R.ESTADO,
    COUNT(*) AS TOTAL_RESERVAS
FROM RESERVA R
GROUP BY
    TO_CHAR(R.FECHA_HORA, 'YYYY-MM'),
    R.ESTADO
ORDER BY MES, R.ESTADO;



-- =========================================================
-- REPORTE 7: INGRESOS POR MUNICIPIO Y TIPO DE PRESTADOR
-- =========================================================

SELECT
    M.NOMBRE AS MUNICIPIO,
    TP.NOMBRE AS TIPO_PRESTADOR,
    COUNT(B.ID_BOLETA) AS BOLETAS_VENDIDAS,
    SUM(B.PRECIO_PAGADO) AS TOTAL_INGRESOS
FROM BOLETA B
JOIN ZONA Z
    ON B.ID_ZONA = Z.ID_ZONA
JOIN FUNCION F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCION A
    ON F.ID_ATRACCION = A.ID_ATRACCION
JOIN PRESTADOR P
    ON A.ID_PRESTADOR = P.ID_PRESTADOR
JOIN MUNICIPIO M
    ON P.ID_MUNICIPIO = M.ID_MUNICIPIO
JOIN TIPO_PRESTADOR TP
    ON P.ID_TIPO_PRESTADOR = TP.ID_TIPO_PRESTADOR
JOIN RESERVA R
    ON B.ID_RESERVA = R.ID_RESERVA
WHERE B.ESTADO IN ('VENDIDA', 'USADA')
  AND R.ESTADO = 'CONFIRMADA'
GROUP BY M.NOMBRE, TP.NOMBRE
ORDER BY TOTAL_INGRESOS DESC;



-- =========================================================
-- REPORTE 8: COMBOS MAS VENDIDOS
-- =========================================================

SELECT
    C.ID_COMBO,
    C.NOMBRE AS COMBO,
    C.PRECIO,
    C.ESTADO,
    COUNT(DISTINCT B.ID_RESERVA) AS RESERVAS_CON_COMBO,
    COUNT(B.ID_BOLETA) AS BOLETAS_DE_COMBO,
    NVL(SUM(B.PRECIO_PAGADO), 0) AS TOTAL_INGRESOS
FROM COMBO C
LEFT JOIN BOLETA B
    ON C.ID_COMBO = B.ID_COMBO
   AND B.ESTADO IN ('VENDIDA', 'USADA')
   AND EXISTS (
       SELECT 1
       FROM RESERVA R
       WHERE R.ID_RESERVA = B.ID_RESERVA
         AND R.ESTADO = 'CONFIRMADA'
   )
GROUP BY
    C.ID_COMBO,
    C.NOMBRE,
    C.PRECIO,
    C.ESTADO
ORDER BY
    RESERVAS_CON_COMBO DESC,
    TOTAL_INGRESOS DESC;



-- =========================================================
-- REPORTE 9: CLIENTES RECURRENTES
-- =========================================================

SELECT
    P.ID_PERFIL,
    P.DOCUMENTO,
    P.NOMBRE AS CLIENTE,
    U.CORREO,
    COUNT(R.ID_RESERVA) AS RESERVAS_CONFIRMADAS,
    MIN(R.FECHA_HORA) AS PRIMERA_RESERVA,
    MAX(R.FECHA_HORA) AS ULTIMA_RESERVA
FROM PERFIL_CLIENTE P
LEFT JOIN USUARIO_SISTEMA U
    ON P.ID_USUARIO = U.ID_USUARIO
JOIN RESERVA R
    ON P.ID_PERFIL = R.ID_PERFIL
WHERE R.ESTADO = 'CONFIRMADA'
GROUP BY
    P.ID_PERFIL,
    P.DOCUMENTO,
    P.NOMBRE,
    U.CORREO
HAVING COUNT(R.ID_RESERVA) >= 2
ORDER BY RESERVAS_CONFIRMADAS DESC, P.NOMBRE;



-- =========================================================
-- REPORTE 10: AUDITORIA DE MENORES SIN ADULTO
-- =========================================================

SELECT
    R.ID_RESERVA,
    P.NOMBRE AS CLIENTE,
    A.NOMBRE AS ATRACCION,
    F.ID_FUNCION,
    F.FECHA,
    COUNT(B.ID_BOLETA) AS BOLETAS_MENORES
FROM RESERVA R
JOIN PERFIL_CLIENTE P
    ON R.ID_PERFIL = P.ID_PERFIL
JOIN BOLETA B
    ON R.ID_RESERVA = B.ID_RESERVA
JOIN TIPO_ENTRADA T
    ON B.ID_TIPO_ENTRADA = T.ID_TIPO_ENTRADA
JOIN ZONA Z
    ON B.ID_ZONA = Z.ID_ZONA
JOIN FUNCION F
    ON Z.ID_FUNCION = F.ID_FUNCION
JOIN ATRACCION A
    ON F.ID_ATRACCION = A.ID_ATRACCION
WHERE T.REQUIERE_ADULTO = 'S'
  AND B.ESTADO IN ('VENDIDA', 'USADA')
  AND NOT EXISTS (
      SELECT 1
      FROM BOLETA BA
      JOIN TIPO_ENTRADA TA
          ON BA.ID_TIPO_ENTRADA = TA.ID_TIPO_ENTRADA
      JOIN ZONA ZA
          ON BA.ID_ZONA = ZA.ID_ZONA
      WHERE BA.ID_RESERVA = R.ID_RESERVA
        AND ZA.ID_FUNCION = F.ID_FUNCION
        AND UPPER(TRIM(TA.NOMBRE)) = 'ADULTO'
        AND BA.ESTADO IN ('VENDIDA', 'USADA')
  )
GROUP BY
    R.ID_RESERVA,
    P.NOMBRE,
    A.NOMBRE,
    F.ID_FUNCION,
    F.FECHA
ORDER BY F.FECHA, R.ID_RESERVA;


